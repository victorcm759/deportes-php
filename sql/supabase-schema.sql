-- Esquema del medallero adaptado a PostgreSQL (Supabase)
-- Ejecutar en el SQL Editor de Supabase ANTES de supabase-data.sql
-- Nota: PostgreSQL pasa a minúsculas los identificadores sin comillas
-- (miColor -> micolor, parcial1A -> parcial1a, resultadoFinal -> resultadofinal).

-- Extensión para comparar sin tildes (como hacía MySQL)
CREATE EXTENSION IF NOT EXISTS unaccent WITH SCHEMA extensions;

-- normalizar('Autonómico') = 'autonomico': comparaciones sin distinguir mayúsculas ni tildes
CREATE OR REPLACE FUNCTION public.normalizar(texto TEXT)
RETURNS TEXT
LANGUAGE sql IMMUTABLE
SET search_path = ''
AS $$ SELECT lower(extensions.unaccent(texto)) $$;

-- Tablas
CREATE TABLE IF NOT EXISTS medallas (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) CHECK (tipo IN ('Autonómico', 'Nacional', 'Internacional')),
    competicion VARCHAR(255),
    deporte VARCHAR(100),
    posicion VARCHAR(20) CHECK (posicion IN ('Oro', 'Plata', 'Bronce', 'Participante')),
    division VARCHAR(100) NULL,
    lugar VARCHAR(100),
    provincia VARCHAR(100),
    comunidad VARCHAR(100),
    pais VARCHAR(100),
    year SMALLINT
);

CREATE TABLE IF NOT EXISTS partidos (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo VARCHAR(20) CHECK (tipo IN ('Autonómico', 'Nacional', 'Internacional')),
    division VARCHAR(20) CHECK (division IN ('Individual', 'Parejas')),
    participante VARCHAR(100),
    fase VARCHAR(20) CHECK (fase IN ('Pool', 'Eliminación', 'Ida', 'Vuelta', 'Triangular')),
    miColor VARCHAR(10) CHECK (miColor IN ('Rojo', 'Azul')),
    colorRival VARCHAR(10) CHECK (colorRival IN ('Rojo', 'Azul')),
    fecha DATE,
    ubicacion VARCHAR(100),
    provincia VARCHAR(100) NULL,
    comunidad VARCHAR(100) NULL,
    pais VARCHAR(100),
    parcial1A INT NOT NULL,
    parcial1B INT NOT NULL,
    parcial2A INT NOT NULL,
    parcial2B INT NOT NULL,
    parcial3A INT NOT NULL,
    parcial3B INT NOT NULL,
    parcial4A INT NOT NULL,
    parcial4B INT NOT NULL,
    desempateA INT NULL,
    desempateB INT NULL,
    resultadoA VARCHAR(3) NOT NULL,
    resultadoB VARCHAR(3) NOT NULL,
    resultadoFinal VARCHAR(10) CHECK (resultadoFinal IN ('Victoria', 'Derrota'))
);

CREATE TABLE IF NOT EXISTS participantes_nacionales (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(100),
    club VARCHAR(100),
    provincia VARCHAR(100),
    comunidad VARCHAR(100),
    year SMALLINT
);

CREATE TABLE IF NOT EXISTS equipos_boccia (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(255),
    integrantes VARCHAR(100),
    club VARCHAR(100),
    comunidad VARCHAR(100),
    year SMALLINT
);

-- Vistas (security_invoker: respetan el RLS de las tablas)
CREATE OR REPLACE VIEW competiciones WITH (security_invoker = true) AS
    SELECT DISTINCT tipo, competicion, lugar, provincia, comunidad, pais, year
    FROM medallas;

CREATE OR REPLACE VIEW competiciones_slalom WITH (security_invoker = true) AS
    SELECT DISTINCT tipo, competicion, lugar, provincia, comunidad, year
    FROM medallas
    WHERE deporte = 'Slalom';

CREATE OR REPLACE VIEW competiciones_boccia WITH (security_invoker = true) AS
    SELECT DISTINCT tipo, competicion, lugar, provincia, comunidad, year
    FROM medallas
    WHERE deporte = 'Boccia';

CREATE OR REPLACE VIEW partidos_por_participante WITH (security_invoker = true) AS
    SELECT participante, SUM(CASE WHEN resultadoFinal = 'Victoria' THEN 1 ELSE 0 END) AS victorias, SUM(CASE WHEN resultadoFinal = 'Derrota' THEN 1 ELSE 0 END) AS derrotas
    FROM partidos
    WHERE division = 'Individual'
    GROUP BY participante
    ORDER BY victorias DESC, derrotas ASC;

CREATE OR REPLACE VIEW partidos_por_parejas WITH (security_invoker = true) AS
    SELECT participante AS pareja, SUM(CASE WHEN resultadoFinal = 'Victoria' THEN 1 ELSE 0 END) AS victorias, SUM(CASE WHEN resultadoFinal = 'Derrota' THEN 1 ELSE 0 END) AS derrotas
    FROM partidos
    WHERE division = 'Parejas'
    GROUP BY participante
    ORDER BY victorias DESC, derrotas ASC;

-- Seguridad: RLS activado con lectura pública (solo SELECT) vía API de Supabase.
-- Las escrituras solo se pueden hacer desde el panel o con la service_role key.
ALTER TABLE medallas ENABLE ROW LEVEL SECURITY;
ALTER TABLE partidos ENABLE ROW LEVEL SECURITY;
ALTER TABLE participantes_nacionales ENABLE ROW LEVEL SECURITY;
ALTER TABLE equipos_boccia ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Lectura pública" ON medallas;
CREATE POLICY "Lectura pública" ON medallas FOR SELECT USING (true);
DROP POLICY IF EXISTS "Lectura pública" ON partidos;
CREATE POLICY "Lectura pública" ON partidos FOR SELECT USING (true);
DROP POLICY IF EXISTS "Lectura pública" ON participantes_nacionales;
CREATE POLICY "Lectura pública" ON participantes_nacionales FOR SELECT USING (true);
DROP POLICY IF EXISTS "Lectura pública" ON equipos_boccia;
CREATE POLICY "Lectura pública" ON equipos_boccia FOR SELECT USING (true);
